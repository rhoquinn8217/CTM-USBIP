int run_device_type_tests()
{
    section("device type: a pad, even with media keys and a keyboard after it");
    CTM_CHECK(device_type::from_descriptor(kGameSir) == "controller");
    CTM_CHECK(device_type::from_descriptor(kProController) == "controller");

    section("device type: a keyboard and a mouse");
    CTM_CHECK(device_type::from_descriptor(kBootKeyboard) == "keyboard");
    CTM_CHECK(device_type::from_descriptor(kBootMouse) == "mouse");

    section("device type: nothing said when the descriptor does not say");
    {
        // A consumer-control remote: its own page, not a controller or keyboard.
        const std::vector<uint8_t> remote = {0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0xC0};
        CTM_CHECK(device_type::from_descriptor(remote).empty());
        const std::vector<uint8_t> vendor = {0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0xC0};
        CTM_CHECK(device_type::from_descriptor(vendor).empty());
        CTM_CHECK(device_type::from_descriptor({}).empty());
        const std::vector<uint8_t> cut = {0x05, 0x01, 0x09};
        CTM_CHECK(device_type::from_descriptor(cut).empty());
    }

    section("device type: a four-byte usage carries its own page");
    {
        // Usage 0x00010005, Game Pad on Generic Desktop, with no Usage Page item.
        const std::vector<uint8_t> extended = {0x0B, 0x05, 0x00, 0x01, 0x00, 0xA1, 0x01, 0xC0};
        CTM_CHECK(device_type::from_descriptor(extended) == "controller");
    }
    return 0;
}
